/**
 * Deepfake Vision AI — Utility Functions
 */

window.sleep = (ms) => new Promise(r => setTimeout(r, ms));

window.formatTimestamp = () => new Date().toISOString();

window.generateInferenceId = () => 'INF_' + Date.now();

window.clamp = (val, min, max) => Math.max(min, Math.min(max, val));

window.lerp = (a, b, t) => a + (b - a) * t;

window.mapRange = (val, inMin, inMax, outMin, outMax) =>
    outMin + ((val - inMin) / (inMax - inMin)) * (outMax - outMin);

window.downloadTextFile = function(content, filename) {
    const blob = new Blob([content], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a); a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
};

